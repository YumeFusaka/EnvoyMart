package yumefusaka.envoymart.agent.core;

/**
 * 一次任务在 Agent 图里的阶段。
 * <p>
 * <b>为什么需要它：</b>图原本只有节点，没有「这个请求现在处在哪一步」这个概念。
 * 节点是执行结构，阶段是<b>对外可观察的状态</b>——两者不是一回事。
 * 有了阶段，前端才能显示「正在规划 / 正在执行 / 等你确认 / 正在核对」，
 * 而不是一个转圈动画从头发到尾；中断恢复才有「从哪一步接着跑」的依据，
 * 而不是把整轮重做一遍。
 * <p>
 * <b>它不是状态机里的状态转移表。</b>本项目的轨迹/派送状态刻意不做流转规则
 * （见 {@code DeliveryStatus}），因为事实记录不该被状态机捆住。这里的阶段不同——
 * 它描述的是<b>一次请求的执行进度</b>，这个进度确实有先后，而且是有限枚举。
 */
public enum TaskStage {

    /** 正在规划：还没有确定要用哪些工具 */
    PLANNING,
    /** 正在执行：计划已定，工具调用进行中 */
    EXECUTING,
    /** 等用户确认：撞上高危操作，图在中途结束 */
    WAITING_USER,
    /** 正在核对：工具跑完了，在评估要不要重规划 */
    CHECKING,
    /** 已完成：回答已产出 */
    DONE
}
