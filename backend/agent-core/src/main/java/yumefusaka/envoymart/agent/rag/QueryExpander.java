package yumefusaka.envoymart.agent.rag;

/**
 * 检索查询扩写器 —— 把一句查询变成「一批可以分别检索的查询」。
 * <p>
 * <b>它补的是什么：</b>三档评测里最弱的一档是语义鸿沟（Hit@3 0.625）：查询与文档
 * 既不共享词元、向量空间里也离得远。这一档丢分的形态不是「排错了」，而是
 * 「那篇文档根本没进候选池」——重排、加权、调大 topK 都救不了没进池子的东西。
 * 扩写是唯一一条把查询本身变得接近文档的路。
 * <p>
 * <b>它发生在指代消解之后。</b>上游（{@code QueryRewriter}）已经把这轮的追问补成了
 * 一条能独立理解的句子，所以扩写器拿到的输入本身就是完整的——它不需要再看对话历史，
 * 也不该再看：再喂一遍历史只会给它一次「把上一轮的内容又编进假想答案」的机会。
 * <p>
 * <b>失败一律降级为 {@link QueryExpansions#none()}。</b>扩写是增强不是主功能，
 * 模型超时、返回坏 JSON、编出一段与问题无关的文字，任何一条都退回「没有扩写」。
 * 代价只是回到改造前，而收益是候选池从「有」变成「有对的」——这个交换比只在一个
 * 方向上成立，所以宁可少扩、不可扩错。
 * <p>
 * <b>实现者必须自己兜住异常</b>，不要把异常抛给检索主流程：调用点在检索链路上，
 * 一次扩写失败不该让用户看不到回答。
 */
public interface QueryExpander {

    /**
     * 不扩写 —— 没配模型、开关关掉、评测基线都落到这里。
     * <p>
     * 它是「改造前的行为」的唯一表示：{@link QueryExpansions#none()} 进到检索里，
     * 路数、顺序、融合与重排与改造前逐位相同。有一个具名的默认实现，是为了让
     * 「扩写没生效」这件事在装配处一眼可见，而不是靠一个 null 去猜。
     */
    QueryExpander NOOP = query -> QueryExpansions.none();

    /**
     * @param query 已消解过指代的检索句
     * @return 扩写结果；无扩写时返回 {@link QueryExpansions#none()}，<b>绝不返回 null</b>
     */
    QueryExpansions expand(String query);
}
