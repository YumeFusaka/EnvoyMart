    /**
     * probe-constipation-3 的真实四句：线上日志的拒绝理由是
     * 「同一引用切片未支撑：数量主体与引用切片不一致」与「本品临床事实没有声明引用来源所属商品」。
     * <p>
     * 两句都不是证据问题，而是解析把排版/指标名当成了药名：
     * <ul>
     *   <li>「怎么吃：初次食用建议…」里的「怎么吃」是字段标签，剥不掉时「初次食」被当成主体；</li>
     *   <li>「每日饮水量建议不少于 1500 毫升」里的「饮水量」是被推荐的对象，不是药名。</li>
     * </ul>
     * 另外两句引用的 [4] 指向唯一的商品说明书，「本品」的归属由**这句引用的切片**唯一确定。
     */
    @Test
    void 现场四句都带有效引用时不得被判无出处() {
        String reply = String.join("\n",
                "**几点提醒（均来自说明书原文）：**",
                "- 怎么吃：初次食用建议从每日 1 袋开始，让肠道逐步适应，一周后可酌情增加 [6]；",
                "- 肠梗阻、肠道狭窄者禁用 [4]；",
                "- 吞咽困难者慎用 [4]；",
                "- 对本品任一成分过敏者禁用 [4]。",
                "- 同时保证充足饮水，每日饮水量建议不少于 1500 毫升 [6]。");
        var verdict = MedicalEvidenceVerifier.verify(true, reply, probeEvidence(), List.of(),
                EvidenceGate.Thresholds.defaults(), Set.of("KB-0024_3", "KB-0024_8"));
        assertThat(verdict.reasons()).as("四句都有逐字支撑的引用切片").isEmpty();
    }

